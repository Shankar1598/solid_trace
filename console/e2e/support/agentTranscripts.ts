import { randomBytes, randomUUID } from 'node:crypto'
import { mkdirSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'

// Fixture transcripts for the Agent sessions flow, in the shape of Claude
// Code's .jsonl files: each line has the cwd and the session id, a reply has
// its model, its effort and its usage, and a subagent has its own file under
// <session>/subagents/. The flow writes them into a Claude projects folder,
// and the real `solidtrace capture` uploads them. Times are a few minutes
// before now, so the Agent sessions page's 7-day range holds them.

export const MODEL = 'claude-opus-5-5'

/** The summary of the long session's /compact, in the shape of Claude Code's. */
export const COMPACTION_SUMMARY = 'This session is being continued from a previous conversation that ran out of context. The summary below covers the earlier portion of the conversation.\n\n<tools-used-before-summary>Agent</tools-used-before-summary>\n\nSummary:\n1. The person asked where the cart code is.'
export const SUBAGENT_MODEL = 'claude-sonnet-5-5'
/** The effort of the main transcript's replies, and of the subagent's. */
export const EFFORT = 'high'
export const SUBAGENT_EFFORT = 'low'

/** The tokens of one request, by kind. */
export type Usage = { input: number; output: number; cacheRead: number; cacheWrite: number }

/** A secret in the shape of an Anthropic API key, made at run time so that no key-shaped literal is in the repo. */
export function fakeAnthropicKey(): string {
  return ['sk', 'ant', 'api03'].join('-') + '-' + randomBytes(30).toString('hex')
}

type Line = Record<string, unknown>

/** One transcript: its lines and the line maker that fills the shared fields. */
class Transcript {
  readonly lines: Line[] = []
  private parent: string | null = null
  private at: number

  constructor(private readonly sessionId: string, private readonly cwd: string, start: Date, private readonly extra: Line = {}) {
    this.at = start.getTime()
  }

  private add(fields: Line): string {
    const uuid = randomUUID()
    this.at += 2_000
    this.lines.push({
      parentUuid: this.parent, isSidechain: false, userType: 'external', cwd: this.cwd, sessionId: this.sessionId,
      version: '2.1.325', gitBranch: 'main', ...this.extra, ...fields, uuid, timestamp: new Date(this.at).toISOString(),
    })
    this.parent = uuid
    return uuid
  }

  person(text: string) {
    this.add({ type: 'user', message: { role: 'user', content: text } })
  }

  reply(content: Line[], usage: Usage, model = MODEL, effort = EFFORT) {
    this.add({
      type: 'assistant', effort, perTurnEffort: effort,
      message: {
        id: `msg_${randomBytes(12).toString('hex')}`, type: 'message', role: 'assistant', model, content,
        stop_reason: content.some(c => c.type === 'tool_use') ? 'tool_use' : 'end_turn',
        usage: {
          input_tokens: usage.input, output_tokens: usage.output,
          cache_read_input_tokens: usage.cacheRead, cache_creation_input_tokens: usage.cacheWrite,
          cache_creation: { ephemeral_5m_input_tokens: usage.cacheWrite, ephemeral_1h_input_tokens: 0 },
        },
      },
    })
  }

  toolResult(toolUseId: string, text: string, toolUseResult: Line = {}) {
    this.add({
      type: 'user', toolUseResult,
      message: { role: 'user', content: [{ type: 'tool_result', tool_use_id: toolUseId, content: text }] },
    })
  }

  /**
   * A /compact as Claude Code writes it: the person's input, a caveat for
   * the model, the command in its tags, the boundary, the summary, and the
   * command's output with the terminal's colour codes.
   */
  compact(summary: string) {
    this.person('/compact')
    this.add({
      type: 'user', isMeta: true,
      message: { role: 'user', content: '<local-command-caveat>Caveat: The messages below were generated by the user while running local commands. DO NOT respond to these messages or otherwise consider them in your response unless the user explicitly asks you to.</local-command-caveat>' },
    })
    this.add({
      type: 'user',
      message: { role: 'user', content: '<command-name>/compact</command-name>\n            <command-message>compact</command-message>\n            <command-args></command-args>' },
    })
    this.add({ type: 'system', subtype: 'compact_boundary', content: 'Conversation compacted', level: 'info', compactMetadata: { trigger: 'manual', preTokens: 12_000 } })
    this.add({ type: 'user', isCompactSummary: true, isVisibleInTranscriptOnly: true, message: { role: 'user', content: summary } })
    this.add({
      type: 'user',
      message: { role: 'user', content: '<local-command-stdout>\u001b[2mCompacted (ctrl+o to see full summary)\u001b[22m</local-command-stdout>' },
    })
  }

  /**
   * A shell command (`! terraform plan`) as Claude Code writes it: the
   * person's command in <bash-input>, then its output in <bash-stdout> and
   * <bash-stderr>, with the terminal's colour codes.
   */
  shell(command: string, stdout: string, stderr: string) {
    this.person(`<bash-input>${command}</bash-input>`)
    this.person(`<bash-stdout>${stdout}</bash-stdout><bash-stderr>${stderr}</bash-stderr>`)
  }

  /** A title line as Claude Code writes it: an ai-title, or a person's /rename (custom-title). No uuid, no time. */
  title(kind: 'ai' | 'custom', text: string) {
    this.lines.push(kind === 'ai'
      ? { type: 'ai-title', aiTitle: text, sessionId: this.sessionId }
      : { type: 'custom-title', customTitle: text, sessionId: this.sessionId })
  }

  text(): string {
    return this.lines.map(l => JSON.stringify(l)).join('\n') + '\n'
  }
}

/** A fixture Agent session: its id and its files, by path relative to the Claude project folder. */
export type FixtureSession = { id: string; files: Record<string, string> }

/** A short Agent session: one person message and one reply. */
export function shortSession(cwd: string, text: string, usage: Usage, start = minutesAgo(20)): FixtureSession {
  const id = randomUUID()
  const main = new Transcript(id, cwd, start)
  main.person(text)
  main.reply([{ type: 'text', text: 'Done.' }], usage)
  return { id, files: { [`${id}.jsonl`]: main.text() } }
}

/**
 * The long Agent session: a person message with a secret, an Agent tool call
 * whose subagent has its own transcript, and a Bash call whose output is
 * past the Log limit of 64 KiB, with a second secret and an end marker
 * after the cut. Claude Code gives it a title, and the person renames it
 * to opts.title; a later title of Claude Code's does not change it. The
 * subagent's own title lines are not the Agent session's.
 */
export function longSession(cwd: string, opts: {
  personText: string; title: string; subagentId: string; subagentReply: string; outputEnd: string; secret: string
  usage: Usage[]; subagentUsage: Usage
}): FixtureSession {
  const id = randomUUID()
  const start = minutesAgo(15)
  const main = new Transcript(id, cwd, start)
  main.person(opts.personText)
  main.reply([{ type: 'tool_use', id: 'toolu_flow_agent', name: 'Agent', input: { description: 'Find the cart code', prompt: 'Find the cart code.' } }], opts.usage[0])
  main.title('ai', 'Find the cart code')

  const sub = new Transcript(id, cwd, new Date(start.getTime() + 3_000), { isSidechain: true, agentId: opts.subagentId })
  // A subagent's prompt is a user line of its own file: not from a person.
  sub.person('Find the cart code.')
  sub.reply([{ type: 'text', text: opts.subagentReply }], opts.subagentUsage, SUBAGENT_MODEL, SUBAGENT_EFFORT)
  sub.title('custom', 'A subagent name')

  main.toolResult('toolu_flow_agent', opts.subagentReply, { agentId: opts.subagentId, status: 'completed' })
  main.title('custom', opts.title)
  main.compact(COMPACTION_SUMMARY)
  main.shell('terraform plan', '\u001b[0m\u001b[1mgoogle_storage_bucket.cart: Refreshing state...\u001b[0m', 'Acquiring state lock.')
  main.reply([{ type: 'tool_use', id: 'toolu_flow_bash', name: 'Bash', input: { command: 'seq 1 20000', description: 'Print many lines' } }], opts.usage[1])
  const lines = Array.from({ length: 12_000 }, (_, i) => `line ${i + 1} of the output`).join('\n')
  main.toolResult('toolu_flow_bash', `${lines}\nkey ${opts.secret}\n${opts.outputEnd}`)
  main.reply([{ type: 'text', text: 'The cart code is in `cart.go`, and the command printed **its lines**.\n\n| file | lines |\n| --- | ---: |\n| cart.go | 20000 |' }], opts.usage[2])
  main.title('ai', 'Find the cart code and print many lines')

  return {
    id,
    files: {
      [`${id}.jsonl`]: main.text(),
      [`${id}/subagents/agent-${opts.subagentId}.jsonl`]: sub.text(),
    },
  }
}

/**
 * An open-pr Agent session: the person starts the skill, whose text comes
 * in as a user line with its own example record. The agent sends the PR's
 * Review record to solidtrace review final in a heredoc, and the final
 * reply gives only the PR. With `inReply`, the session is one from before
 * that command: the final reply ends with the record in its block.
 */
export function openPrSession(cwd: string, opts: { exampleRecord: string; record: string; minutesAgo: number; inReply?: boolean }): FixtureSession {
  const id = randomUUID()
  const main = new Transcript(id, cwd, minutesAgo(opts.minutesAgo))
  const usage = { input: 3, output: 30, cacheRead: 300, cacheWrite: 30 }
  main.person('/solidtrace-skills:open-pr')
  if (opts.inReply) {
    main.person(`End the reply with the record:\n\n\`\`\`solidtrace-pr-record\n${opts.exampleRecord}\n\`\`\``)
    main.reply([{ type: 'text', text: `Opened the PR.\n\n\`\`\`solidtrace-pr-record\n${opts.record}\n\`\`\`` }], usage)
  } else {
    main.person(`Send the record:\n\n\`\`\`\nsolidtrace review final <<'SOLIDTRACE_RECORD_END'\n${opts.exampleRecord}\nSOLIDTRACE_RECORD_END\n\`\`\``)
    const toolUseId = `toolu_${randomBytes(8).toString('hex')}`
    main.reply([{ type: 'tool_use', id: toolUseId, name: 'Bash', input: { command: `solidtrace review final <<'SOLIDTRACE_RECORD_END'\n${opts.record}\nSOLIDTRACE_RECORD_END`, description: 'Send the Review record' } }], usage)
    const parsed = JSON.parse(opts.record) as { round: number; findings: { outcome: string }[] }
    const fixed = parsed.findings.filter(f => f.outcome === 'fixed').length
    main.toolResult(toolUseId, `record: round ${parsed.round}, ${parsed.findings.length} findings, ${fixed} fixed`)
    main.reply([{ type: 'text', text: 'Opened the PR.' }], usage)
  }
  return { id, files: { [`${id}.jsonl`]: main.text() } }
}

/** Writes the session's files under the Claude project folder; answers the main transcript's path. */
export function writeSession(projectDir: string, session: FixtureSession): string {
  for (const [path, text] of Object.entries(session.files)) {
    const file = join(projectDir, path)
    mkdirSync(dirname(file), { recursive: true })
    writeFileSync(file, text)
  }
  return join(projectDir, `${session.id}.jsonl`)
}

function minutesAgo(minutes: number): Date {
  return new Date(Date.now() - minutes * 60_000)
}
