#!/bin/sh
# Sets up Claude Code on this machine for SolidTrace: the solidtrace CLI of a
# release, the SolidTrace marketplace, the capture plugin, the review plugin
# and the sign-in.
#
#   curl -fsSL https://raw.githubusercontent.com/Shankar1598/solid_trace/main/cli/setup-claude-code.sh | sh
#
# SOLIDTRACE_VERSION sets the release (default: the newest), and
# SOLIDTRACE_INSTALL_DIR the folder of solidtrace (default ~/.local/bin).

# Through curl | sh, the script is on stdin, so the prompts cannot read the
# terminal, and sh is not always bash. So download the script into a file and
# run it with bash, with the terminal on stdin.
if [ -z "${BASH_VERSION:-}" ] || [ ! -t 0 ]; then
  url="${SOLIDTRACE_SETUP_URL:-https://raw.githubusercontent.com/Shankar1598/solid_trace/main/cli/setup-claude-code.sh}"
  tmp="$(mktemp)" || exit 1
  curl -fsSL "$url" -o "$tmp" || { echo "setup: could not download $url" >&2; exit 1; }
  SOLIDTRACE_SETUP_TMP="$tmp" exec bash "$tmp" "$@" </dev/tty
fi
[ -n "${SOLIDTRACE_SETUP_TMP:-}" ] && trap 'rm -f "$SOLIDTRACE_SETUP_TMP"' EXIT

# The wizard writes no .env file.
export ENV_FILE=/dev/null

#
# A wizard walks a human through a manual procedure, step by step.
# Generated by the /wizard skill.
#
# Everything above the "STAGES" marker is the wizard library: do not hand-edit
# it. Author the per-step stages below the marker.

set -euo pipefail

# ──────────────────────────────────────────────────────────────────────────
# Wizard library: delightful, consistent UX, identical across every wizard.
# ──────────────────────────────────────────────────────────────────────────

if [[ -t 1 ]] && command -v tput >/dev/null 2>&1 && [[ "$(tput colors 2>/dev/null || echo 0)" -ge 8 ]]; then
  BOLD=$(tput bold); DIM=$(tput dim); RESET=$(tput sgr0)
  BLUE=$(tput setaf 4); GREEN=$(tput setaf 2); YELLOW=$(tput setaf 3); RED=$(tput setaf 1)
else
  BOLD=""; DIM=""; RESET=""; BLUE=""; GREEN=""; YELLOW=""; RED=""
fi

# Author sets this at the top of the stages section.
TOTAL_STAGES=0

_STAGE_INDEX=0
ENV_FILE="${ENV_FILE:-.env}"
WRITTEN_ENV=()    # KEYs written to ENV_FILE this run
WRITTEN_SECRET=() # secret NAMEs set this run
SKIPPED=()        # things we couldn't do (e.g. gh missing)

# _clear wipes the terminal so only the current step is on screen. No-op when
# output isn't a terminal, so piped logs stay readable.
_clear() {
  [[ -t 1 ]] || return 0
  if command -v tput >/dev/null 2>&1; then tput clear; else printf '\033[2J\033[3J\033[H'; fi
}

# banner "Title" shows the opening frame: what this wizard does.
banner() {
  _clear
  printf '\n%s%s  %s%s\n' "$BOLD" "$BLUE" "$1" "$RESET"
  printf '%s  %s stages%s\n\n' "$DIM" "$TOTAL_STAGES" "$RESET"
  printf '%s  You drive the browser; this wizard tells you exactly what to do and\n' "$DIM"
  printf '  captures the values you copy back. Stop any time with Ctrl-C and re-run\n'
  printf '  later, since it remembers values already saved.%s\n' "$RESET"
  pause "Ready to start?"
}

# stage "Name" clears the screen, then announces a stage and shows progress.
# Clearing keeps only the current step on screen.
stage() {
  _clear
  _STAGE_INDEX=$((_STAGE_INDEX + 1))
  printf '\n%s%s▸ Stage %s/%s · %s%s\n' \
    "$BOLD" "$BLUE" "$_STAGE_INDEX" "$TOTAL_STAGES" "$1" "$RESET"
}

# say "..." prints a plain instruction line.
say()  { printf '  %s\n' "$1"; }
# step "..." is a numbered-feeling action the human takes in the browser.
step() { printf '  %s•%s %s\n' "$BLUE" "$RESET" "$1"; }
note() { printf '  %s%s%s\n' "$DIM" "$1" "$RESET"; }
warn() { printf '  %s⚠ %s%s\n' "$YELLOW" "$1" "$RESET"; }

# open_url URL opens it in the human's browser, cross-platform incl. WSL.
open_url() {
  local url="$1"
  printf '  %s↗ opening%s %s\n' "$GREEN" "$RESET" "$url"
  { if   command -v wslview     >/dev/null 2>&1; then wslview "$url"
    elif command -v explorer.exe >/dev/null 2>&1; then explorer.exe "$url"
    elif command -v xdg-open    >/dev/null 2>&1; then xdg-open "$url"
    elif command -v open        >/dev/null 2>&1; then open "$url"
    else warn "couldn't open a browser; visit it manually: $url"; fi
  } >/dev/null 2>&1 || warn "couldn't open a browser, so visit it manually: $url"
}

# pause "msg" waits for the human to confirm they've done the manual part.
pause() {
  printf '  %s%s%s ' "$DIM" "${1:-Press Enter to continue}" "$RESET"
  read -r _ || true
}

# confirm "question" is a y/N gate; returns success on yes.
confirm() {
  local reply=""
  printf '  %s? %s [y/N] ' "$YELLOW" "$1"
  read -r reply || true
  [[ "$reply" =~ ^[Yy] ]]
}

# _existing KEY: current value of KEY in ENV_FILE, if any.
_existing() {
  [[ -f "$ENV_FILE" ]] || return 1
  local line; line=$(grep -E "^${1}=" "$ENV_FILE" | tail -n1) || return 1
  printf '%s' "${line#*=}"
}

# ask KEY "Prompt" reads a value into $KEY. Offers the existing .env value as
# a default on re-runs (Enter keeps it). Visible input (non-secret).
ask() {
  local key="$1" prompt="$2" current input
  current=$(_existing "$key" || true)
  if [[ -n "$current" ]]; then
    printf '  %s%s%s %s[Enter keeps current]%s ' "$BOLD" "$prompt" "$RESET" "$DIM" "$RESET"
  else
    printf '  %s%s%s ' "$BOLD" "$prompt" "$RESET"
  fi
  read -r input || true
  [[ -z "$input" && -n "$current" ]] && input="$current"
  printf -v "$key" '%s' "$input"
}

# ask_secret KEY "Prompt" is like ask, but input is hidden.
ask_secret() {
  local key="$1" prompt="$2" current input
  current=$(_existing "$key" || true)
  if [[ -n "$current" ]]; then
    printf '  %s%s%s %s[Enter keeps current]%s ' "$BOLD" "$prompt" "$RESET" "$DIM" "$RESET"
  else
    printf '  %s%s%s ' "$BOLD" "$prompt" "$RESET"
  fi
  read -rs input || true
  printf '\n'
  [[ -z "$input" && -n "$current" ]] && input="$current"
  printf -v "$key" '%s' "$input"
}

# write_env KEY VALUE upserts KEY=VALUE into ENV_FILE (creates it; replaces
# any existing line). Idempotent.
write_env() {
  local key="$1" value="$2" tmp
  touch "$ENV_FILE"
  tmp=$(mktemp)
  grep -vE "^${key}=" "$ENV_FILE" > "$tmp" || true
  printf '%s=%s\n' "$key" "$value" >> "$tmp"
  mv "$tmp" "$ENV_FILE"
  WRITTEN_ENV+=("$key")
  printf '  %s✓ wrote%s %s → %s\n' "$GREEN" "$RESET" "$key" "$ENV_FILE"
}

# set_secret NAME VALUE sets a GitHub Actions repo secret via gh. Falls back
# to a warning (and records it) if gh is unavailable or unauthenticated.
set_secret() {
  local name="$1" value="$2"
  if command -v gh >/dev/null 2>&1 && gh auth status >/dev/null 2>&1; then
    if printf '%s' "$value" | gh secret set "$name" >/dev/null 2>&1; then
      WRITTEN_SECRET+=("$name")
      printf '  %s✓ set%s GitHub secret %s\n' "$GREEN" "$RESET" "$name"
      return
    fi
  fi
  SKIPPED+=("GitHub secret $name (set it manually: gh secret set $name)")
  warn "skipped GitHub secret $name: gh not ready; set it later"
}

# set_var NAME VALUE sets a GitHub Actions repo variable (non-secret).
set_var() {
  local name="$1" value="$2"
  if command -v gh >/dev/null 2>&1 && gh auth status >/dev/null 2>&1; then
    if gh variable set "$name" --body "$value" >/dev/null 2>&1; then
      printf '  %s✓ set%s GitHub variable %s\n' "$GREEN" "$RESET" "$name"
      return
    fi
  fi
  SKIPPED+=("GitHub variable $name")
  warn "skipped GitHub variable $name, gh not ready; set it later"
}

# finish clears, then shows a closing summary of everything configured.
finish() {
  _clear
  printf '\n%s%s  ✓ Setup complete%s\n' "$BOLD" "$GREEN" "$RESET"
  (( ${#WRITTEN_ENV[@]} ))    && note "wrote ${#WRITTEN_ENV[@]} value(s) to $ENV_FILE: ${WRITTEN_ENV[*]}"
  (( ${#WRITTEN_SECRET[@]} )) && note "set ${#WRITTEN_SECRET[@]} GitHub secret(s): ${WRITTEN_SECRET[*]}"
  if (( ${#SKIPPED[@]} )); then
    printf '\n'; warn "still to do by hand:"
    for s in "${SKIPPED[@]}"; do note "  - $s"; done
  fi
  printf '\n'
}


# ──────────────────────────────────────────────────────────────────────────
# STAGES
# ──────────────────────────────────────────────────────────────────────────

REPOSITORY="Shankar1598/solid_trace"
MARKETPLACE_FILE="$HOME/.local/share/solidtrace/.claude-plugin/marketplace.json"
BIN_DIR="${SOLIDTRACE_INSTALL_DIR:-$HOME/.local/bin}"
ST="$BIN_DIR/solidtrace"

fail() { warn "$1"; exit 1; }

# plugin_installed NAME is true when Claude Code has the plugin NAME.
plugin_installed() {
  claude plugin list 2>/dev/null | grep -qE "(^|[[:space:]])$1\$"
}

# install_plugin NAME installs the plugin NAME, or updates it to the
# marketplace's version.
install_plugin() {
  if plugin_installed "$1"; then
    claude plugin update "$1" || fail "could not update $1"
  else
    claude plugin install "$1" || fail "could not install $1"
  fi
}

# confirm_yes "question" is a Y/n gate: Enter is yes.
confirm_yes() {
  local reply=""
  printf '  %s? %s [Y/n]%s ' "$YELLOW" "$1" "$RESET"
  read -r reply || true
  [[ ! "$reply" =~ ^[Nn] ]]
}

CLAUDE_SETTINGS="$HOME/.claude/settings.json"

# settings_env_has KEY is true when Claude Code's user settings set KEY in env.
settings_env_has() {
  [[ -f "$CLAUDE_SETTINGS" ]] && command -v python3 >/dev/null 2>&1 || return 1
  KEY="$1" FILE="$CLAUDE_SETTINGS" python3 -c '
import json, os, sys
d = json.load(open(os.environ["FILE"]))
sys.exit(0 if (d.get("env") or {}).get(os.environ["KEY"]) else 1)'
}

# write_settings_env KEY VALUE sets KEY in env of Claude Code's user settings,
# and keeps the other settings. The file then has mode 600, as it holds a
# token. The value goes through the environment, not the command line.
write_settings_env() {
  command -v python3 >/dev/null 2>&1 || return 1
  mkdir -p "$(dirname "$CLAUDE_SETTINGS")"
  KEY="$1" VALUE="$2" FILE="$CLAUDE_SETTINGS" python3 -c '
import json, os
f = os.environ["FILE"]
d = json.load(open(f)) if os.path.exists(f) and os.path.getsize(f) else {}
d.setdefault("env", {})[os.environ["KEY"]] = os.environ["VALUE"]
tmp = f + ".tmp"
with open(os.open(tmp, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600), "w") as out:
    json.dump(d, out, indent=2)
    out.write("\n")
os.replace(tmp, f)'
}

TOTAL_STAGES=8

banner "SolidTrace for Claude Code"

stage "Choose the release"
for tool in curl claude; do
  command -v "$tool" >/dev/null 2>&1 || fail "$tool is necessary, and it is not on PATH"
done
latest="$(curl -fsSLI -o /dev/null -w '%{url_effective}' "https://github.com/$REPOSITORY/releases/latest")" \
  || fail "could not find the newest release of $REPOSITORY"
latest="${latest##*/}"
VERSION="${SOLIDTRACE_VERSION:-$latest}"
say "The newest release is $latest."
note "Use the release of your SolidTrace server. Console's Capture setup page gives it."
ask CHOSEN "Release to install [Enter for $VERSION]:"
[[ -n "$CHOSEN" ]] && VERSION="$CHOSEN"
[[ "$VERSION" =~ ^v[0-9] ]] || fail "a release is a tag such as v0.24.0, not $VERSION"
RELEASE_URL="https://github.com/$REPOSITORY/releases/download/$VERSION"
say "The wizard installs $VERSION."
pause

stage "Install the solidtrace CLI"
say "Now: $("$ST" version 2>/dev/null || echo "no solidtrace in $BIN_DIR")."
say "The release's install.sh installs solidtrace $VERSION in $BIN_DIR."
note "It installs the file only when its SHA-256 is the one in the release's SHA256SUMS."
pause "Press Enter to install"
curl -fsSL "$RELEASE_URL/install.sh" | SOLIDTRACE_VERSION="$VERSION" SOLIDTRACE_INSTALL_DIR="$BIN_DIR" sh \
  || fail "the CLI install failed"
case ":$PATH:" in
  *":$BIN_DIR:"*) ;;
  *) SKIPPED+=("add $BIN_DIR to PATH, so that the capture plugin finds solidtrace") ;;
esac
pause

stage "Add the SolidTrace marketplace"
say "Claude Code cannot add the marketplace file from a github.com URL."
say "So the wizard downloads it to $MARKETPLACE_FILE, and adds it from there."
pause "Press Enter to continue"
mkdir -p "$(dirname "$MARKETPLACE_FILE")"
if [[ -f "$MARKETPLACE_FILE" ]]; then
  cp -f "$MARKETPLACE_FILE" "$MARKETPLACE_FILE.previous"
  note "kept the earlier file as $MARKETPLACE_FILE.previous"
fi
curl -fsSL -o "$MARKETPLACE_FILE" "$RELEASE_URL/marketplace.json" \
  || fail "could not download $RELEASE_URL/marketplace.json"
if claude plugin marketplace list 2>/dev/null | grep -qF "$MARKETPLACE_FILE"; then
  claude plugin marketplace update solidtrace || fail "could not update the solidtrace marketplace"
else
  claude plugin marketplace add "$MARKETPLACE_FILE" || fail "could not add the solidtrace marketplace"
fi
pause

stage "Install the capture plugin"
say "solidtrace@solidtrace uploads the Agent sessions of your Organization's Captured repositories."
say "An Agent session in another repository stays on this machine."
pause "Press Enter to install"
install_plugin solidtrace@solidtrace
pause

stage "Install the review plugin"
say "solidtrace-skills@solidtrace gives /solidtrace-skills:code-review, deep-review,"
say "open-pr, update-pr and try-pr. They record each finding of a review."
REVIEW_PLUGIN=no
if confirm_yes "Install the review plugin?"; then
  install_plugin solidtrace-skills@solidtrace
  REVIEW_PLUGIN=yes
else
  SKIPPED+=("the review plugin: claude plugin install solidtrace-skills@solidtrace")
fi
pause

stage "Bitbucket token"
BITBUCKET_SKIPPED="on bitbucket.org, open-pr and update-pr need BITBUCKET_TOKEN in env of $CLAUDE_SETTINGS; without it, open-pr gives a link to a new PR"
if [[ "$REVIEW_PLUGIN" != yes ]]; then
  say "The review plugin is not installed, so it needs no token."
elif [[ -n "${BITBUCKET_TOKEN:-}" ]] || settings_env_has BITBUCKET_TOKEN; then
  say "BITBUCKET_TOKEN is set already. The wizard does not change it."
else
  say "On bitbucket.org, open-pr and update-pr use BITBUCKET_TOKEN to open the PR,"
  say "read its comments and build statuses, and reply to the comments."
  note "GitHub repositories need no token: the skills use gh."
  step "In Bitbucket, open the workspace settings → Access tokens, or a repository's"
  step "Repository settings → Access tokens. A repository's token works for that repository only."
  step "Create a token that can write pull requests and read the repositories, and copy it."
  ask_secret BB_TOKEN "Paste the token (Enter skips):"
  if [[ -z "$BB_TOKEN" ]]; then
    SKIPPED+=("$BITBUCKET_SKIPPED")
  else
    code="$(printf 'Authorization: Bearer %s\n' "$BB_TOKEN" \
      | curl -s -o /dev/null -w '%{http_code}' -H @- https://api.bitbucket.org/2.0/user || true)"
    save=yes
    if [[ "$code" != 200 ]]; then
      warn "Bitbucket answered $code to the token, not 200."
      confirm "Save it anyway?" || save=no
    fi
    if [[ "$save" == no ]]; then
      SKIPPED+=("$BITBUCKET_SKIPPED")
    elif write_settings_env BITBUCKET_TOKEN "$BB_TOKEN"; then
      printf '  %s✓ wrote%s BITBUCKET_TOKEN → env of %s\n' "$GREEN" "$RESET" "$CLAUDE_SETTINGS"
    else
      SKIPPED+=("python3 is necessary to write $CLAUDE_SETTINGS: add BITBUCKET_TOKEN to its env by hand")
    fi
  fi
  unset BB_TOKEN
fi
pause

stage "Sign in"
if "$ST" capture status 2>&1 | grep -q "signed in to"; then
  say "This machine is signed in already:"
  "$ST" capture status 2>&1 | grep "signed in to" | sed 's/^ */  /'
else
  say "In Console, open Settings → Agent sessions → Capture setup."
  say "Its sign-in step gives your Console URL and your Ingest URL."
  ask CONSOLE_URL "Console URL (such as https://solidtrace.example.com):"
  ask INGEST_URL "Ingest URL (such as https://solidtrace.example.com:4443):"
  device=()
  if [[ "$(uname -s)" != Darwin && -z "${DISPLAY:-}${WAYLAND_DISPLAY:-}" ]]; then
    device=(--device)
    note "This machine has no browser: the CLI gives a code for Console's device page."
  fi
  say "Read the approval text: it names the repositories that upload, and who can read them."
  "$ST" login ${device[@]+"${device[@]}"} --ingest-url "$INGEST_URL" "$CONSOLE_URL" || fail "the sign-in failed"
fi
pause

stage "Check"
claude plugin list 2>/dev/null | grep -A3 -E "solidtrace(-skills)?@solidtrace\$" | sed 's/^/  /'
printf '\n'
"$ST" capture status 2>&1 | sed -n '1,8p' | sed 's/^/  /'
printf '\n'
say "Restart Claude Code: a running session does not load the new plugins."
pause "Press Enter to finish"

finish
